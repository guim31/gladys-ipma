#!/usr/bin/env node
// -----------------------------------------------------------------------------
// Development tool: regenerate the static table of the IPMA forecast
// locations (src/locations-data.js) and the options of the `location` select
// of the manifest from an IPMA `locations.json` file.
//
//   node scripts/build-locations.mjs [path/to/locations.json]
//
// Default input: test/fixtures/ipma/locations.json (a real response of
// https://api.ipma.pt/public-data/forecast/locations.json). The ids of the
// locations (globalIdLocal) are the device external ids: an id that
// disappears from a new list orphans the devices built on it, so compare the
// diff before committing a regenerated table.
// -----------------------------------------------------------------------------

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';

const root = new URL('..', import.meta.url);
const input = process.argv[2] ?? fileURLToPath(new URL('test/fixtures/ipma/locations.json', root));
const dataPath = fileURLToPath(new URL('src/locations-data.js', root));
const manifestPath = fileURLToPath(new URL('gladys-assistant-integration.json', root));

const raw = JSON.parse(await readFile(input, 'utf8'));
const list = Array.isArray(raw) ? raw : raw.data;

const rows = list
  .map((entry) => [
    Number(entry.globalIdLocal),
    entry.local.trim(),
    Number(entry.idDistrito),
    Number(entry.idConcelho),
    entry.idAreaAviso,
    Number(Number(entry.latitude).toFixed(4)),
    Number(Number(entry.longitude).toFixed(4)),
  ])
  .sort((a, b) => a[0] - b[0]);

const source = `// -----------------------------------------------------------------------------
// GENERATED by scripts/build-locations.mjs from IPMA's locations.json — do not
// edit by hand. One row per forecast location:
// [globalIdLocal, name, district id, municipality id, warning area, lat, lon]
// Data: IPMA (Instituto Português do Mar e da Atmosfera), open data.
// -----------------------------------------------------------------------------

export const LOCATION_ROWS = ${JSON.stringify(rows)};
`;
const options = { ...(await prettier.resolveConfig(dataPath)), filepath: dataPath };
await writeFile(dataPath, await prettier.format(source, options));

// The manifest select lists the same locations, sorted by label. A place name
// does not translate: the labels carry the mandatory `en` text only (Gladys
// falls back to it), which keeps the manifest under the store's 100 KB.
const { LOCATIONS, locationLabel } = await import(`../src/locations.js?${Date.now()}`);
const manifestText = await readFile(manifestPath, 'utf8');
const manifest = JSON.parse(manifestText);
const field = manifest.config_schema.find((entry) => entry.key === 'location');
field.options = [...LOCATIONS]
  .sort((a, b) => locationLabel(a).localeCompare(locationLabel(b), 'pt'))
  .map((location) => ({ value: String(location.id), label: { en: locationLabel(location) } }));
const manifestOptions = { ...(await prettier.resolveConfig(manifestPath)), filepath: manifestPath };
await writeFile(
  manifestPath,
  await prettier.format(JSON.stringify(manifest, null, 2), manifestOptions),
);
console.log(`${rows.length} locations written to src/locations-data.js and the manifest`);
